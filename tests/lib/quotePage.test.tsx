import { cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react"
import { afterEach, beforeEach, expect, it, vi } from "vitest"
import { MemoryRouter } from "react-router-dom"
import { QuotePage } from "@/pages/Quote/QuotePage"
const state = vi.hoisted(() => ({ quote: vi.fn() }))
vi.mock("@/lib/api", () => ({ API: { quote: state.quote } }))
vi.mock("@/lib/queries", () => ({ useServicesQuery: () => ({ data: [{ slug: "web", title: "تطوير المواقع", icon: "web", description: "تصميم وتطوير المواقع" }, { slug: "mobile", title: "تطبيقات الجوال", icon: "mobile", description: "تطبيقات أندرويد وآيفون" }] }) }))
afterEach(cleanup)
beforeEach(() => state.quote.mockReset())
/** Open a searchable select by its label and pick the option with this name. */
function choose(label: string, option: RegExp) {
  fireEvent.click(screen.getByLabelText(label))
  fireEvent.click(screen.getByRole("option", { name: option }))
}
function start() {
  render(<MemoryRouter><QuotePage onToast={vi.fn()} /></MemoryRouter>)
  fireEvent.click(screen.getByRole("button", { name: /تطوير المواقع/ }))
  fireEvent.click(screen.getByRole("button", { name: /الخطوة التالية/ }))
  fireEvent.click(screen.getByRole("button", { name: "دولار أمريكي" }))
  fireEvent.click(screen.getByRole("button", { name: "4,000 – 10,000" }))
  fireEvent.click(screen.getByRole("button", { name: /مرن/ }))
  fireEvent.click(screen.getByRole("button", { name: /الخطوة التالية/ }))
}
it("shows no validation errors until the visitor submits, then corrects them as they type", () => {
  start()
  expect(screen.queryByRole("alert")).toBeNull()
  expect(document.querySelector('[aria-invalid="true"]')).toBeNull()
  fireEvent.click(screen.getByRole("button", { name: /إرسال طلب عرض السعر/ }))
  const name = screen.getByLabelText(/الاسم الكامل/)
  expect(name).toHaveFocus()
  fireEvent.change(name, { target: { value: "إبراهيم الشامي" } })
  expect(name).toHaveAttribute("aria-invalid", "false")
  fireEvent.click(screen.getByRole("button", { name: /رجوع/ }))
  fireEvent.click(screen.getByRole("button", { name: /الخطوة التالية/ }))
  expect(screen.getByLabelText(/الاسم الكامل/)).toHaveValue("إبراهيم الشامي")
  expect(screen.getByText("بيانات التواصل").closest("li")).toHaveAttribute("aria-current", "step")
})
it("uses the chosen country, normalizes the phone and sends the budget range", async () => {
  state.quote.mockResolvedValue({})
  start()
  fireEvent.change(screen.getByLabelText(/الاسم الكامل/), { target: { value: "إبراهيم الشامي" } })
  fireEvent.change(screen.getByLabelText(/البريد الإلكتروني/), { target: { value: "test@example.com" } })
  choose("الدولة / مفتاح الاتصال", /المملكة المتحدة/)
  fireEvent.change(screen.getByLabelText(/رقم الهاتف/), { target: { value: "020 7946 0018" } })
  fireEvent.change(screen.getByLabelText(/تفاصيل ونبذة/), { target: { value: "أريد تطوير موقع إلكتروني للشركة" } })
  fireEvent.click(screen.getByRole("button", { name: /إرسال طلب عرض السعر/ }))
  await waitFor(() => expect(state.quote).toHaveBeenCalledTimes(1))
  expect(state.quote.mock.calls[0][0].phone).toBe("+442079460018")
  expect(state.quote.mock.calls[0][0].budget).toBe("4,000 – 10,000 USD")
  expect(state.quote.mock.calls[0][0].service).toBe("web")
})
it("accepts an exact amount in any currency, digits only, and keeps it on return", () => {
  render(<MemoryRouter><QuotePage onToast={vi.fn()} /></MemoryRouter>)
  fireEvent.click(screen.getByRole("button", { name: /تطوير المواقع/ }))
  fireEvent.click(screen.getByRole("button", { name: /الخطوة التالية/ }))
  fireEvent.click(screen.getByRole("button", { name: /مرن/ }))
  expect(screen.getByRole("button", { name: /الخطوة التالية/ })).toBeDisabled()
  fireEvent.click(screen.getByRole("button", { name: "مبلغ آخر" }))
  const amount = () => screen.getByLabelText("المبلغ")
  // An untouched field is not an error.
  expect(amount()).toHaveAttribute("aria-invalid", "false")
  fireEvent.change(amount(), { target: { value: "abc" } })
  expect(amount()).toHaveValue("")
  fireEvent.change(amount(), { target: { value: "0" } })
  expect(amount()).toHaveAttribute("aria-invalid", "true")
  fireEvent.change(amount(), { target: { value: "٢٥٠٠ ريال" } })
  expect(amount()).toHaveValue("2500")
  choose("العملة", /ريال يمني/)
  fireEvent.click(screen.getByRole("button", { name: /الخطوة التالية/ }))
  fireEvent.click(screen.getByRole("button", { name: /رجوع/ }))
  expect(amount()).toHaveValue("2500")
  expect(screen.getByLabelText("العملة")).toHaveAttribute("data-value", "YER")
})
it("lets the visitor ask for several services at once", async () => {
  state.quote.mockResolvedValue({})
  render(<MemoryRouter><QuotePage onToast={vi.fn()} /></MemoryRouter>)
  fireEvent.click(screen.getByRole("button", { name: /تطوير المواقع/ }))
  fireEvent.click(screen.getByRole("button", { name: /تطبيقات الجوال/ }))
  expect(screen.getByRole("button", { name: /تطوير المواقع/ })).toHaveAttribute("aria-pressed", "true")
  expect(screen.getByRole("button", { name: /تطبيقات الجوال/ })).toHaveAttribute("aria-pressed", "true")
  fireEvent.click(screen.getByRole("button", { name: /الخطوة التالية/ }))
  fireEvent.click(screen.getByRole("button", { name: "لم أحدد بعد" }))
  fireEvent.click(screen.getByRole("button", { name: /مرن/ }))
  fireEvent.click(screen.getByRole("button", { name: /الخطوة التالية/ }))
  fireEvent.change(screen.getByLabelText(/الاسم الكامل/), { target: { value: "إبراهيم الشامي" } })
  fireEvent.change(screen.getByLabelText(/البريد الإلكتروني/), { target: { value: "test@example.com" } })
  fireEvent.change(screen.getByLabelText(/رقم الهاتف/), { target: { value: "771234567" } })
  fireEvent.change(screen.getByLabelText(/تفاصيل ونبذة/), { target: { value: "أريد موقعًا وتطبيقًا للشركة" } })
  fireEvent.click(screen.getByRole("button", { name: /إرسال طلب عرض السعر/ }))
  await waitFor(() => expect(state.quote).toHaveBeenCalledTimes(1))
  expect(state.quote.mock.calls[0][0].service).toBe("web, mobile")
  expect(state.quote.mock.calls[0][0].budget).toBe("لم أحدد بعد")
  // The visitor stays on the page and sees what was sent, with a way to follow up.
  const done = await screen.findByRole("status")
  expect(done).toHaveTextContent("وصلنا طلبك، إبراهيم")
  expect(done).toHaveTextContent("تطوير المواقع، تطبيقات الجوال")
  expect(screen.getByRole("link", { name: /تابع عبر واتساب/ })).toHaveAttribute("href", expect.stringContaining("wa.me/"))
  expect(screen.queryByRole("button", { name: /إرسال طلب عرض السعر/ })).toBeNull()
})
