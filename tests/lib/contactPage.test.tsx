import { cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react"
import { afterEach, beforeEach, expect, it, vi } from "vitest"
import { ContactPage } from "@/pages/Contact/ContactPage"
const state = vi.hoisted(() => ({ contact: vi.fn(), addLead: vi.fn() }))
vi.mock("@/lib/api", () => ({ API: { contact: state.contact } }))
vi.mock("@/lib/leadStore", () => ({ addLead: state.addLead }))
afterEach(cleanup)
beforeEach(() => { vi.clearAllMocks(); state.contact.mockReset() })
function fill() {
  fireEvent.change(screen.getByLabelText(/الاسم الكامل/), { target: { value: "إبراهيم الشامي" } })
  fireEvent.change(screen.getByLabelText(/البريد الإلكتروني/), { target: { value: "ibrahim@example.com" } })
  fireEvent.change(screen.getByLabelText(/رقم الهاتف/), { target: { value: "+967784440429" } })
  fireEvent.change(screen.getByLabelText(/^رسالتك/), { target: { value: "أريد تطوير موقع جديد لشركتي" } })
}
it("focuses the first invalid field and does not send an empty form", () => {
  render(<ContactPage onToast={vi.fn()} />)
  fireEvent.click(screen.getByRole("button", { name: /إرسال الرسالة/ }))
  expect(screen.getByLabelText(/الاسم الكامل/)).toHaveFocus()
  expect(screen.getByLabelText(/الاسم الكامل/)).toHaveAttribute("aria-invalid", "true")
  expect(state.contact).not.toHaveBeenCalled()
})
it("confirms successful submission inline and resets submitted fields", async () => {
  state.contact.mockResolvedValue({})
  render(<ContactPage onToast={vi.fn()} />)
  fill()
  fireEvent.click(screen.getByRole("button", { name: /إرسال الرسالة/ }))
  expect(await screen.findByRole("status")).toHaveTextContent("وصلتنا رسالتك بنجاح")
  expect(state.contact).toHaveBeenCalledTimes(1)
  expect(state.addLead).toHaveBeenCalledTimes(1)
  expect(screen.getByLabelText(/الاسم الكامل/)).toHaveValue("")
})
it("retains user input when the request fails and allows retry", async () => {
  state.contact.mockRejectedValue(new Error("تعذر الاتصال بالخادم"))
  render(<ContactPage onToast={vi.fn()} />)
  fill()
  fireEvent.click(screen.getByRole("button", { name: /إرسال الرسالة/ }))
  expect(await screen.findByRole("alert")).toHaveTextContent("تعذر الاتصال بالخادم")
  expect(screen.getByLabelText(/الاسم الكامل/)).toHaveValue("إبراهيم الشامي")
  expect(state.addLead).not.toHaveBeenCalled()
  await waitFor(() => expect(screen.getByRole("button", { name: /إرسال الرسالة/ })).toBeEnabled())
})
it("validates on blur and clears a corrected field error while typing", () => {
  render(<ContactPage onToast={vi.fn()} />)
  const email = screen.getByLabelText(/البريد الإلكتروني/)
  fireEvent.change(email, { target: { value: "invalid" } })
  expect(email).toHaveAttribute("aria-invalid", "false")
  fireEvent.blur(email)
  expect(email).toHaveAttribute("aria-invalid", "true")
  fireEvent.change(email, { target: { value: "valid@example.com" } })
  expect(email).toHaveAttribute("aria-invalid", "false")
  expect(screen.getByRole("progressbar")).toHaveAttribute("aria-valuenow", "1")
})
it("shows server field errors without losing the message", async () => {
  state.contact.mockRejectedValue(Object.assign(new Error("راجع بيانات التواصل"), { errors: { email: ["هذا البريد غير متاح"] } }))
  render(<ContactPage onToast={vi.fn()} />)
  fill()
  fireEvent.click(screen.getByRole("button", { name: /إرسال الرسالة/ }))
  expect(await screen.findByText("هذا البريد غير متاح")).toBeInTheDocument()
  expect(screen.getByLabelText(/البريد الإلكتروني/)).toHaveFocus()
  expect(screen.getByLabelText(/^رسالتك/)).toHaveValue("أريد تطوير موقع جديد لشركتي")
})
it("prevents repeat submissions while a request is pending", async () => {
  let finish!: (value: object) => void
  state.contact.mockImplementation(() => new Promise(resolve => { finish = resolve }))
  render(<ContactPage onToast={vi.fn()} />)
  fill()
  const form = screen.getByRole("form", { name: "أرسل رسالتك" })
  fireEvent.submit(form)
  fireEvent.submit(form)
  expect(state.contact).toHaveBeenCalledTimes(1)
  expect(screen.getByLabelText(/الاسم الكامل/)).toBeDisabled()
  finish({})
  await screen.findByRole("status")
  expect(screen.getByRole("progressbar")).toHaveAttribute("aria-valuenow", "0")
})
it("rejects a phone value made only of separators", () => {
  render(<ContactPage onToast={vi.fn()} />)
  fill()
  fireEvent.change(screen.getByLabelText(/رقم الهاتف/), { target: { value: "-------" } })
  fireEvent.click(screen.getByRole("button", { name: /إرسال الرسالة/ }))
  expect(state.contact).not.toHaveBeenCalled()
  expect(screen.getByLabelText(/رقم الهاتف/)).toHaveAttribute("aria-invalid", "true")
})
it("revalidates when changing country and sends a normalized international number", async () => {
  state.contact.mockResolvedValue({})
  render(<ContactPage onToast={vi.fn()} />)
  fill()
  const phone = screen.getByLabelText(/رقم الهاتف/)
  fireEvent.change(phone, { target: { value: "020 7946 0018" } })
  fireEvent.blur(phone)
  expect(phone).toHaveAttribute("aria-invalid", "true")
  fireEvent.click(screen.getByLabelText("الدولة / مفتاح الاتصال"))
  fireEvent.click(screen.getByRole("option", { name: /المملكة المتحدة/ }))
  expect(phone).toHaveAttribute("aria-invalid", "false")
  fireEvent.click(screen.getByRole("button", { name: /إرسال الرسالة/ }))
  await screen.findByRole("status")
  expect(state.contact.mock.calls[0][0].get("phone")).toBe("+442079460018")
  expect(state.addLead.mock.calls[0][0].phone).toBe("+442079460018")
})
